import { test, expect, type Page } from '@playwright/test'

async function contentFilters(page: Page) {
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Content filters', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Content filters', exact: true })).toBeVisible()
}

test('shopping and settings are separate; browsing preferences persist and apply', async ({ page }) => {
  await page.goto('/')
  const shopping = page.getByRole('navigation', { name: 'Shopping', exact: true })
  const categories = page.getByRole('navigation', { name: 'Shopping categories', exact: true })
  await expect(shopping.getByRole('button', { name: 'Products', exact: true })).toBeVisible()
  await expect(shopping.getByRole('button', { name: 'Wallet', exact: true })).toHaveCount(0)
  await expect(categories.getByRole('button', { name: 'Books', exact: true })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Settings', exact: true })).toBeHidden()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Settings', exact: true })).toBeFocused()
  await expect(page.getByRole('navigation', { name: 'Settings', exact: true })).toBeHidden()
  await contentFilters(page)
  await expect(page.getByRole('navigation', { name: 'Settings', exact: true })).toBeHidden()
  await expect(page.getByLabel('Search stores and listings', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Content rating', exact: true })).toHaveCount(0)
  await page.getByLabel('Sensitive listings', { exact: true }).selectOption('cover')
  await page.getByRole('switch', { name: 'Hide weapons', exact: true }).check()
  await page.getByRole('textbox', { name: 'Blocked words', exact: true }).fill('notebook')
  await page.getByRole('switch', { name: 'Safe mode', exact: true }).uncheck()
  await expect(page.getByLabel('Sensitive listings', { exact: true })).toBeDisabled()
  await expect(page.getByRole('switch', { name: 'Hide weapons', exact: true })).toBeDisabled()
  await expect(page.getByRole('textbox', { name: 'Blocked words', exact: true })).toBeEnabled()
  await page.reload()
  await contentFilters(page)
  await expect(page.getByRole('switch', { name: 'Safe mode', exact: true })).not.toBeChecked()
  await expect(page.getByLabel('Sensitive listings', { exact: true })).toHaveValue('cover')
  await expect(page.getByRole('switch', { name: 'Hide weapons', exact: true })).toBeChecked()
  await expect(page.getByRole('textbox', { name: 'Blocked words', exact: true })).toHaveValue('notebook')
  await page.getByRole('button', { name: 'Products', exact: true }).click()
  await page.getByLabel('Search stores and listings', { exact: true }).fill('notebook')
  await expect(page.getByRole('button', { name: 'View Clothbound notebook', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Store labels', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Store labels', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Save label', exact: true })).toBeVisible()
})

test('a hidden product can be restored from content filters', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Search stores and listings', { exact: true }).fill('Clothbound notebook')
  await page.getByRole('button', { name: 'View Clothbound notebook', exact: true }).click()
  await page.getByRole('button', { name: 'Hide this listing', exact: true }).click()
  await contentFilters(page)
  await page.locator('summary').filter({ hasText: 'Hidden sellers & listings' }).click()
  await page.getByRole('button', { name: 'Unhide listing Clothbound notebook', exact: true }).click()
  await expect(page.getByText('No hidden sellers or listings.', { exact: true })).toBeVisible()
  await page.locator('summary').filter({ hasText: 'Label sources' }).click()
  await expect(page.getByRole('heading', { name: 'Add a label source', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Follow source', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Products', exact: true }).click()
  await page.getByLabel('Search stores and listings', { exact: true }).fill('Clothbound notebook')
  await expect(page.getByRole('button', { name: 'View Clothbound notebook', exact: true })).toBeVisible()
})

test('the mobile drawer keeps utilities accessible and preferences fit a narrow screen', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Wallet', exact: true })).toBeInViewport()
  await contentFilters(page)
  await expect(page.getByRole('button', { name: 'Open navigation', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('heading', { name: 'Content filters', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  const cards = page.locator('.ob-settings-card')
  for (const card of await cards.all()) {
    const bounds = await card.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(320)
  }
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await page.getByRole('button', { name: 'Tools', exact: true }).click()
  await expect(page.getByRole('heading', { name: /^Tools/ })).toBeVisible()
})

