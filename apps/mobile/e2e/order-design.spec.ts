async function nav(page: Page, name: string, group?: string) {
 const opener = page.getByRole('button', { name: 'Open navigation', exact: true }); if (await opener.isVisible()) await opener.click()
 const scope = group ? page.getByRole('navigation', { name: group, exact: true }) : page
 await scope.getByRole('button', { name, exact: true }).click()
}
