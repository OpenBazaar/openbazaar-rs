test('Monero subaddresses copy in full on a narrow screen', async ({page,context}) => {
 await context.grantPermissions(['clipboard-read','clipboard-write'])
 await page.setViewportSize({width:320,height:900})
 const address='7'+'A'.repeat(94)
 const order={...base,payment:{rail:'xmr',network:'stagenet',subaddress:address,uri:`monero:${address}?tx_amount=0.04`,amountPiconero:'40000000000',receivedPiconero:'0',overpaidPiconero:'0',confirmationsNeeded:10}}
 await page.route('**/orders',route=>route.fulfill({json:{orders:[order]}}))
 await page.route('**/orders/*',route=>route.fulfill({json:order}))
 await page.goto('/'); await nav(page,'Your orders')
 await page.getByRole('button',{name:'Order from Trial Ceramics',exact:true}).click()
 await page.getByRole('button',{name:'Copy monero subaddress',exact:true}).click()
 await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe(address)
 await expect(page.getByRole('button',{name:'Copied',exact:true})).toBeVisible()
 expect(await page.locator('.ob-content').evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBeTruthy()
})
