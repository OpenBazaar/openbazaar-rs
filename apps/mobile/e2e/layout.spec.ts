import { test, expect, type Page } from '@playwright/test'

async function navigate(page: Page, name: string) {
  const opener = page.getByRole('button', { name: 'Open navigation', exact: true })
  if (await opener.isVisible()) await opener.click()
  await page.getByRole('button', { name, exact: true }).click()
}
async function settings(page: Page, name: string) {
  const opener = page.getByRole('button', { name: 'Open navigation', exact: true })
  if (await opener.isVisible()) await opener.click()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name, exact: true }).click()
}
async function fits(page: Page) {
  const layout = await page.locator('.ob-content').evaluate(e => {
    const inner = e.querySelector('.ob-content-inner')!
    const style = getComputedStyle(inner)
    return { width: e.clientWidth, scroll: e.scrollWidth, left: parseFloat(style.paddingLeft), right: parseFloat(style.paddingRight), bottom: parseFloat(style.paddingBottom) }
  })
  expect(layout.scroll).toBeLessThanOrEqual(layout.width + 1)
  expect(layout.left).toBeGreaterThanOrEqual(20)
  expect(layout.right).toBeGreaterThanOrEqual(20)
  expect(layout.bottom).toBeGreaterThanOrEqual(40)
  const contrasts = await page.locator('.ob-primary:not(:disabled)').evaluateAll(buttons => {
    const luminance = (color: string) => {
      const values = color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map(v => { const s = v / 255; return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4 })
      return values[0] * 0.2126 + values[1] * 0.7152 + values[2] * 0.0722
    }
    return buttons.map(button => {
      const style = getComputedStyle(button)
      const a = luminance(style.color), b = luminance(style.backgroundColor)
      return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05)
    })
  })
  for (const contrast of contrasts) expect(contrast).toBeGreaterThanOrEqual(4.5)
  for (const qr of await page.getByRole('img', { name: 'Bitcoin payment QR code', exact: true }).all()) {
    const box = await qr.boundingBox()
    if (box) expect(Math.abs(box.width - box.height)).toBeLessThan(1)
  }
}

for (const [width, height, dark] of [[320, 740, false], [768, 1024, true], [1366, 900, false]] as const) {
  test(`shopping, address, checkout, payment and settings fit ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height })
    await page.goto('/')
    await expect(page.getByRole('heading', { name: /^All products/ })).toBeVisible()
    if (await page.getByRole('switch', { name: 'Dark mode', exact: true }).isChecked() !== dark)
      await page.getByRole('switch', { name: 'Dark mode', exact: true }).click()
    await fits(page)
    await navigate(page, 'Saved goods')
    await expect(page.getByRole('heading', { name: 'No saved products', exact: true })).toBeVisible()
    await fits(page)
    await navigate(page, 'Your bag')
    await expect(page.getByRole('heading', { name: 'Your bag is empty', exact: true })).toBeVisible()
    await fits(page)
    await navigate(page, 'Products')
    await page.locator('.ob-advanced-filters summary').click()
    await fits(page)
    await page.getByLabel('Search stores and listings', { exact: true }).fill('no such product in this test')
    await expect(page.getByRole('heading', { name: 'No matching products', exact: true })).toBeVisible()
    await fits(page)
    await page.getByLabel('Search stores and listings', { exact: true }).fill('Paperback novel')
    await page.getByRole('button', { name: 'View Paperback novel', exact: true }).click()
    await expect(page.getByLabel('Search stores and listings', { exact: true })).toHaveCount(0)
    await fits(page)
    await page.getByRole('button', { name: 'Buy now', exact: true }).click()
    await page.getByRole('button', { name: 'Back to product', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Paperback novel', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Save for later', exact: true }).click()
    await page.getByRole('button', { name: 'Add to bag', exact: true }).click()
    await navigate(page, 'Saved goods')
    await expect(page.getByRole('button', { name: 'View Paperback novel', exact: true })).toBeVisible()
    await fits(page)
    await settings(page, 'Addresses')
    await page.getByRole('button', { name: 'Add an address', exact: true }).click()
    await fits(page)
    for (const [label, value] of Object.entries({ 'Address label': `Layout ${width}`, 'Full name': 'Test Buyer', 'Street address': '1 Test Street', 'Apartment / suite (optional)': 'Suite 4', City: 'Test City', 'State / region': 'Test State', 'Postal code': '00000', Country: 'Test Country' }))
      await page.getByLabel(label, { exact: true }).fill(value)
    await page.getByLabel('Use as my default address', { exact: true }).check()
    await page.getByRole('button', { name: 'Save address', exact: true }).click()
    const address = page.locator('.ob-address-card').filter({ hasText: `Layout ${width}` })
    await expect(address).toBeVisible()
    await fits(page)
    await address.getByRole('button', { name: 'Edit address', exact: true }).click()
    await expect(page.getByLabel('Apartment / suite (optional)', { exact: true })).toHaveValue('Suite 4')
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await navigate(page, 'Your bag')
    await fits(page)
    await page.getByRole('button', { name: 'Continue to checkout', exact: true }).click()
    await expect(page.locator('.ob-selected-address')).toContainText('Suite 4')
    await fits(page)
    await page.getByRole('button', { name: 'Place order', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Order created', exact: true })).toBeVisible()
    await page.locator('.ob-external-payment summary').click()
    await expect(page.getByRole('img', { name: 'Bitcoin payment QR code', exact: true })).toBeVisible()
    await fits(page)
    await navigate(page, 'Your orders')
    await page.getByRole('button', { name: 'Order from Marlow Goods', exact: true }).first().click()
    await page.locator('.ob-external-payment summary').click()
    await expect(page.getByRole('img', { name: 'Bitcoin payment QR code', exact: true })).toBeVisible()
    await fits(page)
    await navigate(page, 'Wallet')
    await page.getByRole('button', { name: 'Receive bitcoin', exact: true }).click()
    await expect(page.getByRole('img', { name: 'Bitcoin payment QR code', exact: true })).toBeVisible()
    await fits(page)
    await page.getByRole('dialog', { name: 'Receive bitcoin', exact: true }).getByRole('button', { name: 'Done', exact: true }).click()
    await settings(page, 'Content filters')
    await fits(page)
    await page.locator('summary').filter({ hasText: 'Hidden sellers & listings' }).click()
    await page.locator('summary').filter({ hasText: 'Label sources' }).click()
    await fits(page)
    await settings(page, 'Store labels')
    await fits(page)
    await page.getByRole('button', { name: 'Save label', exact: true }).click()
    await expect(page.getByText('Signed.', { exact: true })).toBeVisible()
    await page.keyboard.press('ControlOrMeta+k')
    await expect(page.getByLabel('Search stores and listings', { exact: true })).toBeFocused()
  })
}

test('local filters and utility pages are accessible when the catalog is unavailable', async ({ page }) => {
  await page.route('**/catalog', route => route.fulfill({ status: 503, json: { error: 'Catalog temporarily unavailable.' } }))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Unable to connect', exact: true })).toBeVisible()
  await settings(page, 'Content filters')
  await expect(page.getByRole('switch', { name: 'Safe mode', exact: true })).toBeEnabled()
  await settings(page, 'Addresses')
  await expect(page.getByRole('button', { name: 'Add an address', exact: true })).toBeVisible()
  await navigate(page, 'Wallet')
  await expect(page.getByRole('heading', { name: 'Your wallet', exact: true })).toBeVisible()
})
