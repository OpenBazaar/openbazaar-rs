import { test, expect } from '@playwright/test'

test.skip(!process.env.OB_SALES_PREVIEW_COUNT, 'Run with OB_SALES_PREVIEW_COUNT=1000 for the isolated preview.')

test('5,000 simulated orders can be browsed, fulfilled and reset without real mutations', async ({ page, request }, info) => {
  await page.setViewportSize({ width: 1366, height: 1000 })
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' })
  await page.goto('/__preview')
  await expect(page.getByText('No funds or real shipments. Changes reset with this preview.', { exact: true })).toBeVisible()
  const app = page.frameLocator('iframe')
  await app.getByRole('navigation', { name: 'Your store', exact: true }).getByRole('button', { name: 'Sales', exact: true }).click()
  await page.locator('#count').selectOption('5000')
  await page.getByRole('button', { name: 'Load / reset', exact: true }).click()
  await expect(app.getByRole('group', { name: 'Filter sales' }).getByRole('button', { name: /^All/ })).toContainText('5,000')
  await app.getByRole('group', { name: 'Filter sales' }).getByRole('button', { name: /^All/ }).click()
  const table = app.getByRole('table', { name: 'Store orders', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(25)
  const pager = app.getByRole('navigation', { name: 'Sales pagination', exact: true })
  await pager.getByRole('button', { name: 'Last page', exact: true }).click()
  await expect(pager).toContainText('Page 200 of 200')
  await expect(app.locator('.ob-order-list-meta')).toContainText('4,976–5,000 of 5,000 sales')
  const reference = (await table.locator('.ob-sales-reference').first().innerText()).match(/#([a-f0-9]{8})/)![1]
  await pager.getByRole('button', { name: 'First page', exact: true }).click()
  await app.getByRole('searchbox', { name: 'Search sales', exact: true }).fill(reference)
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await app.getByRole('button', { name: 'Reset search & dates', exact: true }).click()
  await app.getByRole('group', { name: 'Filter sales' }).getByRole('button', { name: /^To fulfill/ }).click()
  await table.getByRole('button', { name: /^Ship order:/ }).first().click()
  await app.getByLabel('Carrier', { exact: true }).fill('Simulation carrier')
  await app.getByLabel('Tracking number', { exact: true }).fill('SIM-PREVIEW-TEST')
  await app.getByRole('button', { name: 'Mark as shipped', exact: true }).click()
  await expect(app.getByRole('heading', { name: 'Awaiting buyer confirmation', exact: true })).toBeVisible()
  await expect(app.getByText('Simulation carrier · SIM-PREVIEW-TEST', { exact: true })).toBeVisible()
  await app.getByRole('button', { name: 'Back to sales', exact: true }).click()
  await expect(app.getByRole('group', { name: 'Filter sales' }).getByRole('button', { name: /^To fulfill/ })).toContainText('1,499')
  await page.getByRole('button', { name: 'Load / reset', exact: true }).click()
  await expect(app.getByRole('group', { name: 'Filter sales' }).getByRole('button', { name: /^To fulfill/ })).toContainText('1,500')
  await app.getByRole('group', { name: 'Filter sales' }).getByRole('button', { name: /^All/ }).click()
  await app.getByRole('combobox', { name: 'Sort sales', exact: true }).selectOption('newest')
  await page.evaluate(async () => { await document.fonts.ready })
  await page.screenshot({ path: info.outputPath('sales-simulation-5000.png') })
  await page.setViewportSize({width:812,height:1000})
  await expect(table.locator('tbody tr').first()).toContainText('1 × Stoneware mug')
  expect((await table.locator('tbody tr').first().boundingBox())!.height).toBeLessThan(140)
  await table.locator('tbody tr').last().scrollIntoViewIfNeeded()
  const toolbar=app.locator('.ob-sales-toolbar')
  const scroller=app.locator('.ob-content')
  await expect.poll(async()=>Math.abs((await toolbar.boundingBox())!.y-(await scroller.boundingBox())!.y)).toBeLessThan(2)
  await expect(app.getByRole('searchbox',{name:'Search sales',exact:true})).toBeInViewport()
  await page.screenshot({path:info.outputPath('sales-compact-812-scrolled.png')})
  await app.getByRole('group',{name:'Filter sales'}).getByRole('button',{name:/^To fulfill/}).click()
  await expect.poll(()=>scroller.evaluate(el=>el.scrollTop)).toBe(0)
  await expect(table.locator('tbody tr').first().getByRole('button')).toHaveText('Ship')
  await page.setViewportSize({width:320,height:1000})
  await table.locator('tbody tr').last().scrollIntoViewIfNeeded()
  await expect(app.getByRole('searchbox',{name:'Search sales',exact:true})).toBeInViewport()
  await expect(app.getByRole('group',{name:'Filter sales'}).getByRole('button',{name:/^To fulfill/})).toBeInViewport()
  await page.screenshot({path:info.outputPath('sales-compact-320-scrolled.png')})
  for (const path of ['/orders/fake/pay', '/checkout', '/unlock', '/store/profile']) {
    const response = await request.post(path, { data: {} })
    expect(response.status()).toBe(405)
    expect(await response.json()).toEqual({ error: 'Simulation only: real payments and node changes are disabled.' })
  }
})
