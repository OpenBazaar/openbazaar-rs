import { test, expect, type Page } from '@playwright/test'

async function nav(page: Page, name: string, group?: string) {
  const menu = page.getByRole('button', { name: 'Open navigation', exact: true })
  if (await menu.isVisible()) await menu.click()
  await (group ? page.getByRole('navigation', { name: group, exact: true }) : page).getByRole('button', { name, exact: true }).click()
}
function fixtures() {
  const now = Math.floor(Date.now() / 1000)
  const orders = Array.from({ length: 1000 }, (_, i) => ({
    id: i.toString(16).padStart(8, '0') + 'a'.repeat(24), created: now - i * 86400, seller: `Merchant ${i}`, storeId: 'c'.repeat(64), status: i % 5 === 4 ? 'Awaiting payment' : 'Completed', settlement: 'direct', network: 'testnet4', itemsSats: 10000 + i, shippingSats: 1000, totalSats: 11000 + i, receivedSats: i % 5 === 4 ? 0 : 11000 + i, confirmations: i % 5 === 4 ? 0 : 1, txids: [], payment: { address: `tb1p${'q'.repeat(58)}`, amountSats: 11000 + i, network: 'testnet4' }, lines: [{ title: `Ceramic order ${String(i).padStart(4, '0')}`, listingHash: 'c'.repeat(64), quantity: 1, kind: 'physical', priceSats: 10000 + i }]
  }))
  const sales = orders.map(order => ({ ...order, status: order.status === 'Awaiting payment' ? 'Paid' : 'Completed', receivedSats: order.totalSats, confirmations: 1, address: order.payment.address, shipTo: 'Test recipient\nTest address' }))
  return { orders, sales, now }
}
async function mock(page: Page, data: ReturnType<typeof fixtures>) {
  await page.route('**/store/profile', async route => {
    const response = await route.fetch()
    await route.fulfill({ json: { ...await response.json(), role: 'seller', setUp: true, name: 'Scale test store' } })
  })
  await page.route('**/orders', route => route.fulfill({ json: { orders: data.orders } }))
  await page.route('**/orders/*', route => route.fulfill({ json: data.orders.find(order => route.request().url().endsWith(order.id)) }))
  await page.route('**/wallet',route=>route.fulfill({json:{network:'testnet4',balance:{totalSats:0,spendableSats:0,confirmedSats:0,pendingSats:0},receiveAddress:'tb1p'+'q'.repeat(58),lastSync:null,syncError:null,activity:[]}}))
  await page.route('**/offers', route => route.fulfill({ json: { offers: [] } }))
  let requests = 0
  await page.route('**/sales', route => { requests++; return route.fulfill({ json: { sales: data.sales } }) })
  return () => requests
}
for (const width of [320, 1366]) test(`1,000 orders remain navigable at ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.emulateMedia({ colorScheme: width === 320 ? 'light' : 'dark', reducedMotion: 'reduce' })
  await page.clock.install()
  const data = fixtures()
  const requests = await mock(page, data)
  await page.goto('/')
  await nav(page, 'Your orders')
  await expect(page.getByRole('group', { name: 'Filter orders' }).getByRole('button', { name: /^All/ })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: /Needs attention/ }).click()
  await expect(page.locator('.ob-order-row')).toHaveCount(25)
  await expect(page.locator('.ob-order-list-meta')).toContainText('1–25 of 200 orders')
  await page.getByRole('group', { name: 'Filter orders' }).getByRole('button', { name: /^All/ }).click()
  await page.getByLabel('Sort orders', { exact: true }).selectOption('newest')
  await expect(page.locator('.ob-order-row').first()).toContainText('Ceramic order 0000')
  const pager = page.getByRole('navigation', { name: 'Orders pagination', exact: true })
  await pager.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(page.locator('.ob-order-row').first()).toContainText('Ceramic order 0025')
  await page.getByLabel('Orders per page', { exact: true }).selectOption('50')
  await expect(page.locator('.ob-order-row')).toHaveCount(50)
  await pager.getByRole('button', { name: 'Last page', exact: true }).click()
  await expect(page.locator('.ob-order-list-meta')).toContainText('951–1,000 of 1,000 orders')
  await page.getByRole('searchbox', { name: 'Search orders', exact: true }).fill('Ceramic order 0999')
  await expect(page.locator('.ob-order-row')).toHaveCount(1)
  await expect(page.locator('.ob-order-list-meta')).toContainText('1–1 of 1 order')
  await page.getByRole('button', { name: 'Reset search & dates', exact: true }).click()
  await page.getByLabel('Order date', { exact: true }).selectOption('7')
  await expect(page.locator('.ob-order-row')).toHaveCount(7)
  await page.getByLabel('Order date', { exact: true }).selectOption('custom')
  const date = new Date((data.now - 100 * 86400) * 1000)
  const day = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`
  await page.getByLabel('From date', { exact: true }).fill(day)
  await page.getByLabel('Through date', { exact: true }).fill(day)
  await expect(page.locator('.ob-order-row')).toHaveCount(1)
  await expect(page.locator('.ob-order-row')).toContainText('Ceramic order 0100')
  expect(await page.locator('.ob-content').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBeTruthy()
  await page.getByRole('button', { name: 'Reset search & dates', exact: true }).click()
  await page.getByLabel('Orders per page', { exact: true }).selectOption('25')
  await page.screenshot({ path: info.outputPath(`buyer-1000-${width}.png`) })

  await nav(page, 'Sales', 'Your store')
  await expect(page.getByRole('button', { name: /To fulfill/ })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.ob-order-row')).toHaveCount(25)
  await expect(page.locator('.ob-order-row').first()).toContainText('Ceramic order 0999')
  await page.getByRole('group', { name: 'Filter sales' }).getByRole('button', { name: /^All/ }).click()
  await page.getByLabel('Sort sales', { exact: true }).selectOption('newest')
  await page.getByRole('button', { name: 'Ship order: Ceramic order 0024', exact: true }).click()
  await page.getByLabel('Tracking number', { exact: true }).fill('UNSENT-DRAFT-123')
  await page.getByLabel('Note to the buyer (optional)', { exact: true }).fill('Draft must survive a refresh')
  data.sales.unshift({ ...data.sales[0], id: 'f'.repeat(32), created: data.now + 60, status: 'Paid' })
  const before = requests()
  await page.clock.fastForward(10100)
  await expect.poll(requests).toBeGreaterThan(before)
  await expect(page.getByLabel('Tracking number', { exact: true })).toHaveValue('UNSENT-DRAFT-123')
  await expect(page.getByLabel('Note to the buyer (optional)', { exact: true })).toHaveValue('Draft must survive a refresh')
  await expect(page.locator('.ob-order-pagination').first()).toContainText('Page 2 of 41')
  await expect(page.locator('.ob-order-row')).toHaveCount(25)
  await page.clock.fastForward(10100)
  await expect.poll(requests).toBeGreaterThan(before + 1)
  await expect(page.getByLabel('Tracking number', { exact: true })).toHaveValue('UNSENT-DRAFT-123')
  expect(await page.locator('.ob-content').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBeTruthy()
  await page.getByRole('button', { name: 'Back to sales', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Sales pagination', exact: true })).toContainText('Page 2 of 41')
  await page.getByRole('button', { name: 'Ship order: Ceramic order 0024', exact: true }).click()
  await expect(page.getByLabel('Tracking number', { exact: true })).toHaveValue('UNSENT-DRAFT-123')
  await page.getByRole('button', { name: 'Back to sales', exact: true }).click()
  await page.getByRole('navigation', { name: 'Sales pagination', exact: true }).getByRole('button', { name: 'First page', exact: true }).click()
  await page.screenshot({ path: info.outputPath(`seller-1000-${width}.png`) })
})

test('quiet sales history refreshes once per minute; active sales refresh in ten seconds', async ({ page }) => {
  await page.clock.install()
  const data = fixtures()
  data.sales = data.sales.map(sale => ({ ...sale, status: 'Completed' }))
  const requests = await mock(page, data)
  await page.goto('/')
  await nav(page, 'Sales', 'Your store')
  await expect(page.locator('.ob-order-row')).toHaveCount(25)
  await page.getByRole('button', { name: 'Refresh sales', exact: true }).click()
  const quiet = requests()
  await page.clock.fastForward(11000)
  expect(requests()).toBe(quiet)
  await page.clock.fastForward(50000)
  await expect.poll(requests).toBe(quiet + 1)
  data.sales[0].status = 'Paid'
  await page.getByRole('button', { name: 'Refresh sales', exact: true }).click()
  await expect(page.getByRole('button', { name: /To fulfill/ })).toContainText('1')
  const active = requests()
  await page.clock.fastForward(10100)
  await expect.poll(requests).toBe(active + 1)
})
